const assert=require('node:assert/strict');
const {filterDays,statistics,format}=require('./analytics.js');
const rows=[{date:'2026-01-01',values:[0]},{date:'2026-01-02',values:[null]},{date:'2026-01-04',values:[4]}];
assert.equal(filterDays(rows,'2026-01-02','2026-01-04').length,2);
assert.equal(filterDays(rows,'2026-02-01','2026-01-01').length,0);
assert.deepEqual(statistics(rows,0),{count:2,mean:2,min:0,max:4});
assert.deepEqual(statistics([],0),{count:0,mean:null,min:null,max:null});
assert.equal(format(null),'Unavailable');assert.equal(format(0),'0');
console.log('PASS: date filtering, empty ranges, null measurements and actual zero values.');
const {selectPointRisks}=require('./analytics.js');
const fs=require('node:fs');
const snapshot=JSON.parse(fs.readFileSync(__dirname+'/assets/coverage-snapshot.json','utf8'));
const ids=new Set(snapshot.feeds['features.json'].map(row=>row.cell_id));
const selected=selectPointRisks(snapshot.feeds['risk.json'],ids);
assert.equal(selected.size,40);
for(const id of ids){const records=snapshot.feeds['risk.json'].filter(row=>row.cell_id===id);assert.equal(selected.get(id).risk_score,Math.max(...records.map(row=>row.risk_score)));}
const one=snapshot.feeds['risk.json'][0];
const historical={...one,ts:'2025-01-01T00:00:00Z',risk_score:1,risk_level:'CRITICAL'};
assert.equal(selectPointRisks([historical,one],new Set([one.cell_id])).get(one.cell_id).ts,one.ts);
assert.equal(selectPointRisks([],ids).size,0);
assert.throws(()=>selectPointRisks([{...one,risk_score:NaN}],ids),/Invalid/);
console.log('PASS: all 40 latest risk badges match supplied forecasts; old timestamps and missing/invalid risk handled.');
const vm=require('node:vm');
const pinNodes=new Map();
const pinContext={dayPinned:false,inspection:0,filtered:[{date:'2026-01-01'},{date:'2026-01-02'}],$:id=>{if(!pinNodes.has(id))pinNodes.set(id,{hidden:false,textContent:'',classList:{toggle(){}}});return pinNodes.get(id);},inspect(index,reveal){this.inspection=index;this.inspected={index,reveal};}};
vm.createContext(pinContext);
const analyticsSource=fs.readFileSync(__dirname+'/analytics.js','utf8');
vm.runInContext(analyticsSource.slice(analyticsSource.indexOf('  function updatePinStatus(){'),analyticsSource.indexOf('  function inspectPointer(')),pinContext);
pinContext.pinDay(0);
assert.equal(pinContext.dayPinned,true);
assert.equal(pinNodes.get('chart-unpin').hidden,false);
assert(pinNodes.get('chart-pin-status').textContent.includes('2026-01-01'));
pinContext.pinDay(1);
assert(pinNodes.get('chart-pin-status').textContent.includes('2026-01-02'));
pinNodes.get('chart-unpin').onclick();
assert.equal(pinContext.dayPinned,false);
assert.equal(pinNodes.get('chart-tooltip').hidden,true);
console.log('PASS: clicking a day pins its details; selecting another day moves the pin; Unpin releases it.');

const analyticsHtml=fs.readFileSync(__dirname+'/analytics.html','utf8');
assert(/<button[^>]*id="chart-unpin"[^>]*>Unpin day<\/button>/.test(analyticsHtml),'Analytics must include the actual Unpin button before attaching its handler');
assert(/<p[^>]*id="chart-pin-status"[^>]*>[^<]*<\/p>/.test(analyticsHtml),'Pin status must be a complete paragraph');
console.log('PASS: pin controls exist as correctly formed HTML elements.');
